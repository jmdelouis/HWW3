    END IF
    CALL PUTI('DIKCUMUL', [DIKCUMUL], 1)
    IF (SSDSC(3) .NE. 0.) CALL PUTR2('CUMULW', CUMULW)
    CLOSE (31)
  END SUBROUTINE WRITE_PARAMS

  SUBROUTINE PUTR(NAME, X, LB)
    CHARACTER(*), INTENT(IN) :: NAME
    REAL, INTENT(IN) :: X(:)
    INTEGER, INTENT(IN) :: LB
    CHARACTER(LEN=16) :: NM
    NM = NAME
    WRITE (31) NM, 'R', 1, LB, SIZE(X), X
  END SUBROUTINE PUTR

  SUBROUTINE PUTI(NAME, X, LB)
    CHARACTER(*), INTENT(IN) :: NAME
    INTEGER, INTENT(IN) :: X(:)
    INTEGER, INTENT(IN) :: LB
    CHARACTER(LEN=16) :: NM
