    CALL PUTR('DELAB', [DELAB], 1); CALL PUTR('ABMIN', [ABMIN], 1)
    CALL PUTR('SED_SG', [SED_SG], 1)
    CALL PUTR('ERFTABLE', ERFTABLE, LBOUND(ERFTABLE, 1)); CALL PUTR('DELXERF', [DELXERF], 1)
    CALL PUTR('XERFMAX', [XERFMAX], 1); CALL PUTI('SIZEERFTABLE', [SIZEERFTABLE], 1)
