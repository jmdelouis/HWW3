  END SUBROUTINE PUTI2

  SUBROUTINE READ_PARTS(R0, A)
    INTEGER, INTENT(IN) :: R0
    REAL, INTENT(OUT) :: A(:)
    INTEGER :: JP, M0, M1
    DO JP = 1, NPART
      M0 = 1 + (JP - 1) * NSIZE
      M1 = MIN(NSEA, JP * NSIZE)
      READ (20, REC=R0 + JP - 1) TMP(1:M1 - M0 + 1)
      A(M0:M1) = TMP(1:M1 - M0 + 1)
    END DO
  END SUBROUTINE READ_PARTS

  SUBROUTINE PUT(X)
    REAL, INTENT(IN) :: X
    POS = POS + 1
    IF (POS .LE. NREC) REC(POS) = X
  END SUBROUTINE PUT

  SUBROUTINE PUTV(X)
    REAL, INTENT(IN) :: X(:)
    INTEGER :: J
    DO J = 1, SIZE(X)
      CALL PUT(X(J))
    END DO
  END SUBROUTINE PUTV

