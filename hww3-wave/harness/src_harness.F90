!> Source-term harness of milestone M2a (docs/differentiable.md, sections
!> 2.3 and 9): calls the source terms of WW3 (the hpc build of dea641c with
!> the HWW3 switches) node by node, on the spectra of a WW3 restart and the
!> wind of a ww3_prnc forcing file, and writes their inputs and outputs, so
!> that each port of hww3-wave can be checked node by node before it enters
!> the time loop.
!>
!> usage (in a directory holding the mod_def.ww3 of the run):
!>   ww3_srcharness RESTART WIND OUT STEP [ISEA ...]
!> RESTART  a FULL restart of the same grid (spectra, level, ice, u*, ASF)
!> WIND     wind.ww3 of ww3_prnc: the first record at or after the restart
!>          time is used, as the absolute 10 m wind
!> OUT      output file (stream, native little-endian), layout below
!> STEP     every STEP-th sea point (MAPSTA = 1) is taken, plus the ISEA
!>          given after it
!>
!> For each node, the calls follow the first iteration of W3SRCE with IT > 0:
!> W3SPR4, W3SIN4 (TAUWBUG pre-call), W3SPR4, then W3SLN1, W3SIN4, W3SNL1,
!> W3SDS4, W3SDB1, W3SBT4; then a full W3SRCE (srce_direct, DTG = 600 s) from
!> the same state.
!>
!> Output: header "HWW3SRC1", NK, NTH, NSPEC, NNODE, NREC (int32), restart
!> time (2 int32), wind time (2 int32), DTG (real32); then NNODE records of
!> ISEA (int32) followed by NREC real32 values:
!>   inputs  DW DEPTH CLATS U10 U10DIR UST0 USTDIR0 ICE ASF FPIS0 D50 PSIC
!>           WN(NK) CG(NK) SPEC0(NSPEC)
!>   spr4a   EMEAN FMEAN FMEAN1 WNMEAN AMAX USTAR USTDIR TAUWX TAUWY CD Z0
!>           CHARN FMEANWS DLWMEAN LLWS(NSPEC, 0 or 1)
!>   sin4a   S(NSPEC) D(NSPEC) TAUWX TAUWY TAUWNX TAUWNY BRLAMBDA(NSPEC)
!>   spr4b   as spr4a
!>   sln1    FHIGH S(NSPEC)
!>   sin4    as sin4a
!>   snl1    S(NSPEC) D(NSPEC)
!>   sds4    S(NSPEC) D(NSPEC) WHITECAP(4)
!>   sdb1    LBREAK (0 or 1) S(NSPEC) D(NSPEC)
!>   sbt4    S(NSPEC) D(NSPEC) TAUBBL(2) BEDFORM(3)
!>   srce    SPEC(NSPEC) DTDYN FCUT USTAR USTDIR TAUWX TAUWY TAUOX TAUOY
!>           TAUWIX TAUWIY TAUWNX TAUWNY PHIAW CHARN TWS PHIOC WHITECAP(4)
!>           TAUBBL(2) TAUICE(2) PHICE TAUOCX TAUOCY WNMEAN FPI SHAVE
!>           ALPHA(NK)
PROGRAM HWW3_SRC_HARNESS
  USE CONSTANTS, ONLY: DWAT, DAIR, TPI, SRCE_DIRECT
  USE W3GDATMD, ONLY: W3NMOD, W3SETG, NK, NTH, NSPEC, SIG, NSEA, ZB, CLATS, &
       DMIN, FFXFM, FFXPM, IQTPE, SED_D50, SED_PSIC
  USE W3WDATMD, ONLY: W3NDAT, W3SETW
  USE W3ADATMD, ONLY: W3NAUX, W3SETA
  USE W3ODATMD, ONLY: W3NOUT, W3SETO, NAPROC, IAPROC
  USE W3IDATMD, ONLY: W3NINP, W3SETI, INFLAGS2
  USE W3IOGRMD, ONLY: W3IOGR
  USE W3SRCEMD, ONLY: W3SRCE
  USE W3SRC4MD, ONLY: W3SPR4, W3SIN4, W3SDS4
  USE W3SNL1MD, ONLY: W3SNL1
  USE W3SLN1MD, ONLY: W3SLN1
  USE W3SDB1MD, ONLY: W3SDB1
  USE W3SBT4MD, ONLY: W3SBT4
  USE W3DISPMD, ONLY: WAVNU3
  USE MPI_F08, ONLY: MPI_INIT, MPI_FINALIZE
  IMPLICIT NONE
  CHARACTER(LEN=1024) :: FRST, FWND, FOUT, ARG
  INTEGER :: NSTEP, NARG, I, IA, ISEA, IK, ITH, IP, NSIZE, NPART, LRECL, IERR, IOS
  INTEGER :: NNODE, NREC, POS, IX, IY, N0, N1
  INTEGER :: RTIME(2), WTIME(2)
  INTEGER, ALLOCATABLE :: NODES(:), MAPTMP(:), ITMP(:)
  LOGICAL, ALLOCATABLE :: TAKE(:)
  REAL, ALLOCATABLE :: WLV(:), ICEA(:), UST(:), USTD(:), ASF(:), FPIS(:), UX(:), UY(:), TMP(:)
  REAL, ALLOCATABLE :: REC(:)
  ! per node
  REAL :: DW, DEPTH, DEPTHBAT, WNBAT, CGBAT, U10, U10D, ICE, COEF, FPI, D50, PSIC
  REAL, ALLOCATABLE :: WN1(:), CG1(:), WN2(:), SPEC0(:), SPEC(:), ALPHA(:)
  REAL, ALLOCATABLE :: VS(:), VD(:), BRL(:), SPECOLD(:), VSIO(:), VDIO(:)
  LOGICAL, ALLOCATABLE :: LLWS(:)
  REAL :: EMEAN, FMEAN, FMEAN1, WNMEAN, AMAX, USTAR, USTDIR, TAUWX, TAUWY, CD, Z0, CHARN
  REAL :: FMEANWS, DLWMEAN, TAUWAX, TAUWAY, FHIGH, DRAT, AS
  REAL :: WHITECAP(4), TAUBBL(2), BEDFORM(3), TAUICE(2)
  LOGICAL :: LBREAK, SHAVEIO
  REAL :: DTDYN, FCUT, TAUOX, TAUOY, TAUWIX, TAUWIY, TAUWNX, TAUWNY, PHIAW, TWS, PHIOC
  REAL :: PHIBBL, PHICE, TAUOCX, TAUOCY, REFLEC(4), BERG, ICEH, ICEF, ICEDMAX
  INTEGER :: REFLED(6)
  REAL, PARAMETER :: DTG = 600.

  CALL MPI_INIT(IERR)
  NARG = COMMAND_ARGUMENT_COUNT()
  IF (NARG .LT. 4) STOP 'usage: ww3_srcharness RESTART WIND OUT STEP [ISEA ...]'
  CALL GET_COMMAND_ARGUMENT(1, FRST)
  CALL GET_COMMAND_ARGUMENT(2, FWND)
  CALL GET_COMMAND_ARGUMENT(3, FOUT)
  CALL GET_COMMAND_ARGUMENT(4, ARG)
  READ (ARG, *) NSTEP

  ! model set-up as ww3_shel, then the model definition (source-term
  ! parameters and tables: INSIN4, INSNL1)
  CALL W3NMOD(1, 6, 6)
  CALL W3NDAT(6, 6)
  CALL W3NAUX(6, 6)
  CALL W3NOUT(6, 6)
  CALL W3NINP(6, 6)
  CALL W3SETG(1, 6, 6)
  CALL W3SETW(1, 6, 6)
  CALL W3SETA(1, 6, 6)
  CALL W3SETO(1, 6, 6)
  CALL W3SETI(1, 6, 6)
  NAPROC = 1
  IAPROC = 1
  CALL W3IOGR('READ', 11, 1)
  INFLAGS2(4) = .TRUE.          ! ice concentration forcing, as in the runs
  WRITE (*, '(A,I8,A,2I4)') ' mod_def read: NSEA', NSEA, ', NK NTH', NK, NTH

  ! restart: spectra, then level, ice, MAPSTA, u*, u* direction, ASF, FPIS
  LRECL = MAX(4 * NSPEC, 4 * (6 + (25 / 4) + (9 / 4) + (29 / 4) + (3 / 4)))
  NSIZE = LRECL / 4
  NPART = 1 + (NSEA - 1) / NSIZE
  ALLOCATE (WLV(NSEA), ICEA(NSEA), MAPTMP(NSEA), UST(NSEA), USTD(NSEA), ASF(NSEA), FPIS(NSEA))
  ALLOCATE (TMP(NSIZE), ITMP(NSIZE))
  OPEN (20, FILE=TRIM(FRST), FORM='UNFORMATTED', ACCESS='DIRECT', RECL=LRECL, &
       CONVERT='BIG_ENDIAN', STATUS='OLD', ACTION='READ')
  READ (20, REC=2) RTIME
  CALL READ_PARTS(NSEA + 4, WLV)
  CALL READ_PARTS(NSEA + 4 + NPART, ICEA)
  DO IP = 1, NPART
    N0 = 1 + (IP - 1) * NSIZE
    N1 = MIN(NSEA, IP * NSIZE)
    READ (20, REC=NSEA + 4 + 2 * NPART + IP - 1) ITMP(1:N1 - N0 + 1)
    MAPTMP(N0:N1) = ITMP(1:N1 - N0 + 1)
  END DO
  CALL READ_PARTS(NSEA + 4 + 3 * NPART, UST)
  CALL READ_PARTS(NSEA + 4 + 4 * NPART, USTD)
  CALL READ_PARTS(NSEA + 4 + 5 * NPART, ASF)
  CALL READ_PARTS(NSEA + 4 + 6 * NPART, FPIS)
  WRITE (*, '(A,2I9)') ' restart time', RTIME

  ! wind: first record at or after the restart time
  ALLOCATE (UX(NSEA), UY(NSEA))
  OPEN (21, FILE=TRIM(FWND), FORM='UNFORMATTED', ACCESS='SEQUENTIAL', &
       CONVERT='BIG_ENDIAN', STATUS='OLD', ACTION='READ')
  READ (21)
  DO
    READ (21, IOSTAT=IOS) WTIME
    IF (IOS .NE. 0) STOP 'wind file ends before the restart time'
    READ (21) UX
    READ (21) UY
    IF (WTIME(1) .GT. RTIME(1) .OR. (WTIME(1) .EQ. RTIME(1) .AND. WTIME(2) .GE. RTIME(2))) EXIT
  END DO
  WRITE (*, '(A,2I9)') ' wind time', WTIME

  ! nodes: every NSTEP-th sea point and the listed ones
  ALLOCATE (TAKE(NSEA))
  TAKE = .FALSE.
  DO ISEA = 1, NSEA, NSTEP
    TAKE(ISEA) = .TRUE.
  END DO
  DO IA = 5, NARG
    CALL GET_COMMAND_ARGUMENT(IA, ARG)
    READ (ARG, *) ISEA
    IF (ISEA .GE. 1 .AND. ISEA .LE. NSEA) TAKE(ISEA) = .TRUE.
  END DO
  DO ISEA = 1, NSEA
    IF (MOD(MAPTMP(ISEA) + 2, 8) - 2 .NE. 1) TAKE(ISEA) = .FALSE.
  END DO
  NNODE = COUNT(TAKE)
  ALLOCATE (NODES(NNODE))
  NNODE = 0
  DO ISEA = 1, NSEA
    IF (TAKE(ISEA)) THEN
      NNODE = NNODE + 1
      NODES(NNODE) = ISEA
    END IF
  END DO

  NREC = (12 + 2 * NK + NSPEC) + 2 * (14 + NSPEC) + 2 * (3 * NSPEC + 4) + (1 + NSPEC) &
       + 2 * NSPEC + (2 * NSPEC + 4) + (1 + 2 * NSPEC) + (2 * NSPEC + 5) + (NSPEC + 30 + NK)
  ALLOCATE (REC(NREC))
  ALLOCATE (WN1(NK), CG1(NK), WN2(NSPEC), SPEC0(NSPEC), SPEC(NSPEC), ALPHA(NK))
  ALLOCATE (VS(NSPEC), VD(NSPEC), BRL(NSPEC), LLWS(NSPEC), SPECOLD(NSPEC), VSIO(NSPEC), VDIO(NSPEC))
  OPEN (30, FILE=TRIM(FOUT), ACCESS='STREAM', FORM='UNFORMATTED', STATUS='REPLACE')
  WRITE (30) 'HWW3SRC1', NK, NTH, NSPEC, NNODE, NREC, RTIME, WTIME, DTG
  DRAT = DAIR / DWAT
  AS = 0.
  DO I = 1, NNODE
    ISEA = NODES(I)
    IX = ISEA
    IY = 1
    POS = 0
    ! inputs, as W3INIT and W3ULEV set the wavenumbers
    DW = MAX(0., WLV(ISEA) - ZB(ISEA))
    DEPTHBAT = MAX(DMIN, -ZB(ISEA))
    CALL WAVNU3(SIG(1), DEPTHBAT, WNBAT, CGBAT)
    IF (WNBAT * DEPTHBAT .GE. 4.) THEN
      DEPTH = DEPTHBAT
    ELSE
      DEPTH = MAX(DMIN, DW)
    END IF
    DO IK = 1, NK
      CALL WAVNU3(SIG(IK), DEPTH, WN1(IK), CG1(IK))
      DO ITH = 1, NTH
        WN2(ITH + (IK - 1) * NTH) = WN1(IK)
      END DO
    END DO
    DEPTH = MAX(DMIN, DW)
    READ (20, REC=ISEA + 2) SPEC0
    U10 = SQRT(UX(ISEA)**2 + UY(ISEA)**2)
    U10D = MOD(TPI + ATAN2(UY(ISEA), UX(ISEA)), TPI)
    ICE = ICEA(ISEA)
    COEF = ASF(ISEA)
    FPI = FPIS(ISEA)
    D50 = SED_D50(ISEA)
    PSIC = SED_PSIC(ISEA)
    CALL PUT(DW); CALL PUT(DEPTH); CALL PUT(CLATS(ISEA)); CALL PUT(U10); CALL PUT(U10D)
    CALL PUT(UST(ISEA)); CALL PUT(USTD(ISEA)); CALL PUT(ICE); CALL PUT(COEF); CALL PUT(FPI)
    CALL PUT(D50); CALL PUT(PSIC)
    CALL PUTV(WN1); CALL PUTV(CG1); CALL PUTV(SPEC0)

    ! first iteration of W3SRCE (IT > 0, TAUWBUG = 1)
    SPEC = SPEC0
    USTAR = UST(ISEA)
    USTDIR = USTD(ISEA)
    TAUWX = 0.
    TAUWY = 0.
    CALL W3SPR4(SPEC, CG1, WN1, EMEAN, FMEAN, FMEAN1, WNMEAN, AMAX, U10, U10D, &
         USTAR, USTDIR, TAUWX, TAUWY, CD, Z0, CHARN, LLWS, FMEANWS, DLWMEAN)
    CALL PUT_SPR4
    CALL W3SIN4(SPEC, CG1, WN2, U10, USTAR, DRAT, AS, U10D, Z0, CD, TAUWX, TAUWY, &
         TAUWAX, TAUWAY, VS, VD, LLWS, IX, IY, BRL)
    CALL PUTV(VS); CALL PUTV(VD); CALL PUT(TAUWX); CALL PUT(TAUWY); CALL PUT(TAUWAX)
    CALL PUT(TAUWAY); CALL PUTV(BRL)
    CALL W3SPR4(SPEC, CG1, WN1, EMEAN, FMEAN, FMEAN1, WNMEAN, AMAX, U10, U10D, &
         USTAR, USTDIR, TAUWX, TAUWY, CD, Z0, CHARN, LLWS, FMEANWS, DLWMEAN)
    CALL PUT_SPR4
    FHIGH = MAX(FFXFM * MAX(FMEAN1, FMEANWS), FFXPM / USTAR)
    CALL W3SLN1(WN1, FHIGH, USTAR, U10D, VS)
    CALL PUT(FHIGH); CALL PUTV(VS)
    CALL W3SIN4(SPEC, CG1, WN2, U10, USTAR, DRAT, AS, U10D, Z0, CD, TAUWX, TAUWY, &
         TAUWAX, TAUWAY, VS, VD, LLWS, IX, IY, BRL)
    CALL PUTV(VS); CALL PUTV(VD); CALL PUT(TAUWX); CALL PUT(TAUWY); CALL PUT(TAUWAX)
    CALL PUT(TAUWAY); CALL PUTV(BRL)
    IF (IQTPE .LE. 0) STOP 'the harness expects the DIA (IQTYPE > 0)'
    CALL W3SNL1(SPEC, CG1, WNMEAN * DEPTH, VS, VD)
    CALL PUTV(VS); CALL PUTV(VD)
    WHITECAP = 0.
    CALL W3SDS4(SPEC, WN1, CG1, USTAR, USTDIR, DEPTH, DAIR, VS, VD, IX, IY, BRL, &
         WHITECAP, DLWMEAN)
    CALL PUTV(VS); CALL PUTV(VD); CALL PUTV(WHITECAP)
    CALL W3SDB1(IX, SPEC, DEPTH, EMEAN, FMEAN, WNMEAN, CG1, LBREAK, VS, VD)
    CALL PUT(MERGE(1., 0., LBREAK)); CALL PUTV(VS); CALL PUTV(VD)
    TAUBBL = 0.
    BEDFORM = 0.
    CALL W3SBT4(SPEC, CG1, WN1, DEPTH, D50, PSIC, TAUBBL, BEDFORM, VS, VD, IX, IY)
    CALL PUTV(VS); CALL PUTV(VD); CALL PUTV(TAUBBL); CALL PUTV(BEDFORM)

    ! a full W3SRCE from the same state
    SPEC = SPEC0
    USTAR = UST(ISEA)
    USTDIR = USTD(ISEA)
    TAUWX = 0.
    TAUWY = 0.
    ALPHA = 0.
    WHITECAP = 0.
    TAUBBL = 0.
    TAUICE = 0.
    BEDFORM = 0.
    REFLEC = 0.
    REFLED = 0
    BERG = 0.
    ICEH = 0.
    ICEF = 0.
    ICEDMAX = 0.
    CALL W3SRCE(SRCE_DIRECT, 1, ISEA, ISEA, IX, IY, 1, SPECOLD, SPEC, VSIO, VDIO, &
         SHAVEIO, ALPHA, WN1, CG1, CLATS(ISEA), DW, U10, U10D, AS, USTAR, USTDIR, &
         0., 0., ICE, ICEH, ICEF, ICEDMAX, REFLEC, REFLED, 1., 1., 1., 1., 1., BERG, &
         FPI, DTDYN, FCUT, DTG, TAUWX, TAUWY, TAUOX, TAUOY, TAUWIX, TAUWIY, TAUWNX, &
         TAUWNY, PHIAW, CHARN, TWS, PHIOC, WHITECAP, D50, PSIC, BEDFORM, PHIBBL, &
         TAUBBL, TAUICE, PHICE, TAUOCX, TAUOCY, WNMEAN, DAIR, COEF)
    CALL PUTV(SPEC); CALL PUT(DTDYN); CALL PUT(FCUT); CALL PUT(USTAR); CALL PUT(USTDIR)
    CALL PUT(TAUWX); CALL PUT(TAUWY); CALL PUT(TAUOX); CALL PUT(TAUOY); CALL PUT(TAUWIX)
    CALL PUT(TAUWIY); CALL PUT(TAUWNX); CALL PUT(TAUWNY); CALL PUT(PHIAW); CALL PUT(CHARN)
    CALL PUT(TWS); CALL PUT(PHIOC); CALL PUTV(WHITECAP); CALL PUTV(TAUBBL); CALL PUTV(TAUICE)
    CALL PUT(PHICE); CALL PUT(TAUOCX); CALL PUT(TAUOCY); CALL PUT(WNMEAN); CALL PUT(FPI)
    CALL PUT(MERGE(1., 0., SHAVEIO)); CALL PUTV(ALPHA)
    IF (POS .NE. NREC) THEN
      WRITE (*, *) 'record length', POS, 'expected', NREC
      STOP 'record layout error'
    END IF
    WRITE (30) ISEA, REC
  END DO
  CLOSE (30)
  WRITE (*, '(A,I8,A,I6,A)') ' wrote', NNODE, ' nodes of', NREC, ' values'
  CALL WRITE_PARAMS(TRIM(FOUT) // '.params')
  CALL MPI_FINALIZE(IERR)

CONTAINS

  !> The model parameters and tables the source terms use, as WW3 holds them
  !> after W3IOGR: records of NAME (16 characters), KIND ('R' real32 or 'I'
  !> int32), NDIM, LBOUND(NDIM), SHAPE(NDIM) (int32) and the values in
  !> Fortran order.
  SUBROUTINE WRITE_PARAMS(FNAME)
    USE CONSTANTS, ONLY: GRAV, KAPPA, NU_AIR, FWTABLE, SIZEFWTABLE, DELAB, ABMIN, SED_SG
    USE W3SBT4MD, ONLY: ERFTABLE, DELXERF, XERFMAX, SIZEERFTABLE
    USE W3SRC4MD, ONLY: TAUT, TAUHFT, TAUHFT2, DELUST, DELALP, DELTAUW, DELU, DELTAIL, &
         TAUWMAX, DIKCUMUL
    USE W3GDATMD, ONLY: CUMULW
    USE W3GDATMD, ONLY: DSIP, DDEN, SIG2, DDEN2, DTH, ECOS, ESIN, XFR, FR1, FACHFA, FACHFE, &
         FACP, FACTI1, FACTI2, XFLT, XREL, FHMAX, DTMAX, DTMIN, FTE, FTF, SSTXFTWN, &
         SSTXFTFTAIL, WWNMEANP, WWNMEANPTAIL, FFXFA, ZZWND, AALPHA, BBETA, ZZALP, &
         TTAUWSHELTER, SSWELLF, SSINTHP, ZZ0RAT, ZZ0MAX, SINTAILPAR, CAPCHNK, SSDSC, &
         SSDSBR, SSDSBT, SSDSP, SSDSDTH, SSDSBM, SSDSBRF1, AAIRCMIN, AAIRGB, SATINDICES, &
         SATWEIGHTS, ICESCALES, SLNC1, FSPM, FSHF, SDBC1, SDBC2, FDONLY, KDCON, KDMN, &
         SNLC1, SNLS1, SNLS2, SNLS3, SBTCX
    USE W3ADATMD, ONLY: NFR, NFRHGH, NFRCHG, NSPECX, NSPECY, &
         IP11, IP12, IP13, IP14, IM11, IM12, IM13, IM14, &
         IP21, IP22, IP23, IP24, IM21, IM22, IM23, IM24, &
         IC11, IC12, IC21, IC22, IC31, IC32, IC41, IC42, &
         IC51, IC52, IC61, IC62, IC71, IC72, IC81, IC82, &
         DAL1, DAL2, DAL3, AF11, AWG1, AWG2, AWG3, AWG4, AWG5, AWG6, AWG7, AWG8, &
         SWG1, SWG2, SWG3, SWG4, SWG5, SWG6, SWG7, SWG8
    USE W3ODATMD, ONLY: FLOGRD
    CHARACTER(*), INTENT(IN) :: FNAME
    OPEN (31, FILE=FNAME, ACCESS='STREAM', FORM='UNFORMATTED', STATUS='REPLACE')
    WRITE (31) 'HWW3PAR1'
    CALL PUTI('NK', [NK], 1); CALL PUTI('NTH', [NTH], 1); CALL PUTI('NSPEC', [NSPEC], 1)
    CALL PUTR('SIG', SIG, LBOUND(SIG, 1)); CALL PUTR('DSIP', DSIP, LBOUND(DSIP, 1))
    CALL PUTR('DDEN', DDEN, 1); CALL PUTR('SIG2', SIG2, 1); CALL PUTR('DDEN2', DDEN2, 1)
    CALL PUTR('ECOS', ECOS, 1); CALL PUTR('ESIN', ESIN, 1)
    CALL PUTR('DTH', [DTH], 1); CALL PUTR('XFR', [XFR], 1); CALL PUTR('FR1', [FR1], 1)
    CALL PUTR('FACHFA', [FACHFA], 1); CALL PUTR('FACHFE', [FACHFE], 1); CALL PUTR('FACP', [FACP], 1)
    CALL PUTR('FACTI1', [FACTI1], 1); CALL PUTR('FACTI2', [FACTI2], 1)
    CALL PUTR('XFLT', [XFLT], 1); CALL PUTR('XREL', [XREL], 1); CALL PUTR('FHMAX', [FHMAX], 1)
    CALL PUTR('DTMAX', [DTMAX], 1); CALL PUTR('DTMIN', [DTMIN], 1); CALL PUTR('DMIN', [DMIN], 1)
    CALL PUTR('FTE', [FTE], 1); CALL PUTR('FTF', [FTF], 1)
    CALL PUTR('SSTXFTWN', [SSTXFTWN], 1); CALL PUTR('SSTXFTFTAIL', [SSTXFTFTAIL], 1)
    CALL PUTR('WWNMEANP', [WWNMEANP], 1); CALL PUTR('WWNMEANPTAIL', [WWNMEANPTAIL], 1)
    CALL PUTR('FFXFM', [FFXFM], 1); CALL PUTR('FFXPM', [FFXPM], 1); CALL PUTR('FFXFA', [FFXFA], 1)
    CALL PUTR('ZZWND', [ZZWND], 1); CALL PUTR('AALPHA', [AALPHA], 1); CALL PUTR('BBETA', [BBETA], 1)
    CALL PUTR('ZZALP', [ZZALP], 1); CALL PUTR('TTAUWSHELTER', [TTAUWSHELTER], 1)
    CALL PUTR('SSWELLF', SSWELLF, LBOUND(SSWELLF, 1)); CALL PUTR('SSINTHP', [SSINTHP], 1)
    CALL PUTR('ZZ0RAT', [ZZ0RAT], 1); CALL PUTR('ZZ0MAX', [ZZ0MAX], 1)
    CALL PUTR('SINTAILPAR', SINTAILPAR, LBOUND(SINTAILPAR, 1))
    CALL PUTR('CAPCHNK', CAPCHNK, LBOUND(CAPCHNK, 1))
    CALL PUTR('SSDSC', SSDSC, LBOUND(SSDSC, 1)); CALL PUTR('SSDSBR', [SSDSBR], 1)
    CALL PUTR('SSDSBT', [SSDSBT], 1); CALL PUTR('SSDSP', [SSDSP], 1)
    CALL PUTR('SSDSDTH', [SSDSDTH], 1); CALL PUTR('SSDSBM', SSDSBM, LBOUND(SSDSBM, 1))
    CALL PUTR('SSDSBRF1', [SSDSBRF1], 1); CALL PUTR('AAIRCMIN', [AAIRCMIN], 1)
    CALL PUTR('AAIRGB', [AAIRGB], 1)
    IF (SSDSDTH .LT. 180.) THEN
      CALL PUTI2('SATINDICES', SATINDICES); CALL PUTR2('SATWEIGHTS', SATWEIGHTS)
    END IF
    CALL PUTR('ICESCALES', ICESCALES, LBOUND(ICESCALES, 1))
    CALL PUTR('SLNC1', [SLNC1], 1); CALL PUTR('FSPM', [FSPM], 1); CALL PUTR('FSHF', [FSHF], 1)
    CALL PUTR('SDBC1', [SDBC1], 1); CALL PUTR('SDBC2', [SDBC2], 1)
    CALL PUTI('FDONLY', [MERGE(1, 0, FDONLY)], 1)
    CALL PUTR('KDCON', [KDCON], 1); CALL PUTR('KDMN', [KDMN], 1); CALL PUTR('SNLC1', [SNLC1], 1)
    CALL PUTR('SNLS1', [SNLS1], 1); CALL PUTR('SNLS2', [SNLS2], 1); CALL PUTR('SNLS3', [SNLS3], 1)
    CALL PUTR('SBTCX', SBTCX, LBOUND(SBTCX, 1)); CALL PUTI('IQTPE', [IQTPE], 1)
    CALL PUTI('NFR', [NFR], 1); CALL PUTI('NFRHGH', [NFRHGH], 1); CALL PUTI('NFRCHG', [NFRCHG], 1)
    CALL PUTI('NSPECX', [NSPECX], 1); CALL PUTI('NSPECY', [NSPECY], 1)
    CALL PUTI('IP11', IP11, LBOUND(IP11, 1)); CALL PUTI('IP12', IP12, LBOUND(IP12, 1))
    CALL PUTI('IP13', IP13, LBOUND(IP13, 1)); CALL PUTI('IP14', IP14, LBOUND(IP14, 1))
    CALL PUTI('IM11', IM11, LBOUND(IM11, 1)); CALL PUTI('IM12', IM12, LBOUND(IM12, 1))
    CALL PUTI('IM13', IM13, LBOUND(IM13, 1)); CALL PUTI('IM14', IM14, LBOUND(IM14, 1))
    CALL PUTI('IP21', IP21, LBOUND(IP21, 1)); CALL PUTI('IP22', IP22, LBOUND(IP22, 1))
    CALL PUTI('IP23', IP23, LBOUND(IP23, 1)); CALL PUTI('IP24', IP24, LBOUND(IP24, 1))
    CALL PUTI('IM21', IM21, LBOUND(IM21, 1)); CALL PUTI('IM22', IM22, LBOUND(IM22, 1))
    CALL PUTI('IM23', IM23, LBOUND(IM23, 1)); CALL PUTI('IM24', IM24, LBOUND(IM24, 1))
    CALL PUTI('IC11', IC11, LBOUND(IC11, 1)); CALL PUTI('IC12', IC12, LBOUND(IC12, 1))
    CALL PUTI('IC21', IC21, LBOUND(IC21, 1)); CALL PUTI('IC22', IC22, LBOUND(IC22, 1))
    CALL PUTI('IC31', IC31, LBOUND(IC31, 1)); CALL PUTI('IC32', IC32, LBOUND(IC32, 1))
    CALL PUTI('IC41', IC41, LBOUND(IC41, 1)); CALL PUTI('IC42', IC42, LBOUND(IC42, 1))
    CALL PUTI('IC51', IC51, LBOUND(IC51, 1)); CALL PUTI('IC52', IC52, LBOUND(IC52, 1))
    CALL PUTI('IC61', IC61, LBOUND(IC61, 1)); CALL PUTI('IC62', IC62, LBOUND(IC62, 1))
    CALL PUTI('IC71', IC71, LBOUND(IC71, 1)); CALL PUTI('IC72', IC72, LBOUND(IC72, 1))
    CALL PUTI('IC81', IC81, LBOUND(IC81, 1)); CALL PUTI('IC82', IC82, LBOUND(IC82, 1))
    CALL PUTR('DAL1', [DAL1], 1); CALL PUTR('DAL2', [DAL2], 1); CALL PUTR('DAL3', [DAL3], 1)
