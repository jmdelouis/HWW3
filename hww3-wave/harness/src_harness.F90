    CALL PUTR('SWG', [SWG1, SWG2, SWG3, SWG4, SWG5, SWG6, SWG7, SWG8], 1)
    CALL PUTR('GRAV', [GRAV], 1); CALL PUTR('KAPPA', [KAPPA], 1); CALL PUTR('NU_AIR', [NU_AIR], 1)
    CALL PUTR('DWAT', [DWAT], 1); CALL PUTR('DAIR', [DAIR], 1)
