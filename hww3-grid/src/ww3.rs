//! Writers: Gmsh 2.2 mesh for WW3 UNST grids, open-boundary node list,
//! namelists, and raw little-endian arrays for the Python post-processing.

use crate::config::{Config, Ww3Params};
use anyhow::Result;
use std::fs::File;
use std::io::{BufWriter, Write};
use std::path::Path;

/// Gmsh 2.2 ASCII: nodes (lon, lat, depth > 0) and triangles (type 2).
pub fn write_msh(path: &Path, lon: &[f64], lat: &[f64], depth: &[f64], tris: &[[u32; 3]]) -> Result<()> {
    let mut w = BufWriter::new(File::create(path)?);
    writeln!(w, "$MeshFormat\n2.2 0 8\n$EndMeshFormat")?;
    writeln!(w, "$Nodes\n{}", lon.len())?;
    for i in 0..lon.len() {
        writeln!(w, "{} {:.10} {:.10} {:.3}", i + 1, lon[i], lat[i], depth[i])?;
    }
    writeln!(w, "$EndNodes\n$Elements\n{}", tris.len())?;
    for (k, t) in tris.iter().enumerate() {
        writeln!(w, "{} 2 3 0 {} 0 {} {} {}", k + 1, k + 1, t[0] + 1, t[1] + 1, t[2] + 1)?;
    }
    writeln!(w, "$EndElements")?;
    Ok(())
}

/// Open-boundary node list in the format read by WW3 `READMSHOBC` (w3triamd.F90):
/// a comment-character line, comment lines, then `index ntag [tags] node` with
/// ntag = 0 and 1-based node indices; a final comment line ends the list.
pub fn write_obc(path: &Path, nodes: &[u32]) -> Result<()> {
    let mut w = BufWriter::new(File::create(path)?);
    writeln!(w, "$ Comments")?;
    writeln!(w, "$ Open boundary points written by hww3-grid ({} nodes)", nodes.len())?;
    for (i, n) in nodes.iter().enumerate() {
        writeln!(w, "{} 0 {}", i + 1, n + 1)?;
    }
    writeln!(w, "$ End of file")?;
    Ok(())
}

pub fn write_grid_nml(path: &Path, cfg: &Config) -> Result<()> {
    let p: &Ww3Params = &cfg.ww3;
    let n = &cfg.name;
    let txt = format!(
        "! ww3_grid.nml generated by hww3-grid for grid '{n}'
! HEALPix multi-resolution unstructured grid, nside {nmin}..{nmax}
&SPECTRUM_NML
  SPECTRUM%XFR       = {xfr}
  SPECTRUM%FREQ1     = {f1}
  SPECTRUM%NK        = {nk}
  SPECTRUM%NTH       = {nth}
  SPECTRUM%THOFF     = {thoff}
/
&RUN_NML
  RUN%FLCX         = T
  RUN%FLCY         = T
  RUN%FLCTH        = T
  RUN%FLCK         = T
  RUN%FLSOU        = T
/
&TIMESTEPS_NML
  TIMESTEPS%DTMAX  = {dtmax:.1}
  TIMESTEPS%DTXY   = {dtxy:.1}
  TIMESTEPS%DTKTH  = {dtkth:.1}
  TIMESTEPS%DTMIN  = {dtmin:.1}
/
&GRID_NML
  GRID%NAME        = 'HWW3 {n}'
  GRID%NML         = 'namelists_{n}.nml'
  GRID%TYPE        = 'UNST'
  GRID%COORD       = 'SPHE'
  GRID%CLOS        = 'NONE'
  GRID%ZLIM        = {zlim}
  GRID%DMIN        = {dmin}
/
&UNST_NML
  UNST%SF          = -1.
  UNST%FILENAME    = '{n}.msh'
  UNST%IDLA        = 4
  UNST%IDFM        = 2
  UNST%FORMAT      = '(20f10.2)'
  UNST%UGOBCFILE   = '{n}.obc'
/
",
        nmin = cfg.nside_min,
        nmax = cfg.nside_max,
        xfr = p.xfr,
        f1 = p.freq1,
        nk = p.nk,
        nth = p.nth,
        thoff = p.dir_offset,
        dtmax = p.dtmax,
        dtxy = p.dtxy,
        dtkth = p.dtkth,
        dtmin = p.dtmin,
        zlim = p.zlim,
        dmin = p.dmin,
    );
    std::fs::write(path, txt)?;
    Ok(())
}

/// Physics/numerics namelist: ST4 defaults and the implicit (PDLIB) scheme.
pub fn write_namelists(path: &Path) -> Result<()> {
    let txt = "\
! namelists generated by hww3-grid: implicit unstructured scheme (PDLIB)
&UNST
  UGOBCAUTO      = F,
  UGOBCDEPTH     = -10.,
  EXPFSN         = F,
  EXPFSPSI       = F,
  EXPFSFCT       = F,
  IMPFSN         = F,
  EXPTOTAL       = F,
  IMPTOTAL       = T,
  IMPREFRACTION  = T,
  IMPFREQSHIFT   = T,
  IMPSOURCE      = T,
  SETUP_APPLY_WLV = F,
  JGS_TERMINATE_MAXITER = T,
  JGS_TERMINATE_DIFFERENCE = T,
  JGS_TERMINATE_NORM = F,
  JGS_LIMITER    = F,
  JGS_USE_JACOBI = T,
  JGS_BLOCK_GAUSS_SEIDEL = T,
  JGS_MAXITER    = 100,
  JGS_PMIN       = 3.0,
  JGS_DIFF_THR   = 1.E-6,
  JGS_NORM_THR   = 1.E-6 /
END OF NAMELISTS
";
    std::fs::write(path, txt)?;
    Ok(())
}

pub fn write_raw<T: Copy>(path: &Path, data: &[T]) -> Result<()> {
    // little-endian platforms only (x86_64, aarch64)
    let bytes = unsafe { std::slice::from_raw_parts(data.as_ptr() as *const u8, std::mem::size_of_val(data)) };
    std::fs::write(path, bytes)?;
    Ok(())
}
